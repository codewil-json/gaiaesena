<script>
import { markRaw } from 'vue'

const FEED_URL = 'https://api.rss2json.com/v1/api.json?rss_url=https%3A%2F%2Fconjur.com.br%2Ffeed%2F'
const SITE_URL = 'https://www.gaiaesena.adv.br'

function stripHtml(value) {
  const parsed = new DOMParser().parseFromString(String(value || ''), 'text/html')
  return parsed.body.textContent.replace(/\s+/g, ' ').trim()
}

function getArticleLink(value) {
  try {
    const url = new URL(value)
    if (url.protocol === 'https:' && (url.hostname === 'conjur.com.br' || url.hostname.endsWith('.conjur.com.br'))) {
      return url.href
    }
  } catch (error) {
    return ''
  }

  return ''
}

export default {
  name: 'ArtigosView',
  data() {
    return {
      articles: [],
      loading: true,
      error: '',
      requestController: null,
      isPrerendering: Boolean(window.__PRERENDER_INJECTED?.prerendering)
    }
  },
  mounted() {
    this.addStructuredData()
    if (this.isPrerendering) {
      this.loading = false
    } else {
      this.loadArticles()
    }
  },
  beforeUnmount() {
    if (this.requestController) {
      this.requestController.abort()
    }
    if (this.structuredDataScript) {
      this.structuredDataScript.remove()
    }
  },
  methods: {
    addStructuredData() {
      const topics = [
        {
          id: 'divorcio-consensual-litigioso',
          headline: 'Divórcio consensual e litigioso: entenda as diferenças',
          description: 'Diferenças entre as modalidades de divórcio, etapas e pontos familiares e patrimoniais que merecem atenção.'
        },
        {
          id: 'guarda-e-convivencia',
          headline: 'Guarda compartilhada: o que significa na prática?',
          description: 'Como funciona a responsabilidade conjunta dos pais e como a convivência considera o melhor interesse dos filhos.'
        },
        {
          id: 'verbas-rescisorias',
          headline: 'Verbas rescisórias: o que conferir ao encerrar um contrato de trabalho',
          description: 'Entenda quais fatores influenciam o cálculo das verbas rescisórias e quais documentos guardar.'
        },
        {
          id: 'beneficio-incapacidade-inss',
          headline: 'Benefício por incapacidade do INSS: como se preparar para o pedido',
          description: 'Requisitos gerais e documentos importantes para organizar um pedido de benefício por incapacidade.'
        }
      ]

      const structuredDataScript = document.createElement('script')
      structuredDataScript.type = 'application/ld+json'
      structuredDataScript.textContent = JSON.stringify({
        '@context': 'https://schema.org',
        '@type': 'CollectionPage',
        name: 'Artigos e orientações jurídicas | Gaia & Sena Advogados Associados',
        description: 'Conteúdos informativos sobre direitos e legislação brasileira.',
        inLanguage: 'pt-BR',
        mainEntity: {
          '@type': 'ItemList',
          itemListElement: topics.map((topic, index) => ({
            '@type': 'ListItem',
            position: index + 1,
            item: {
              '@type': 'Article',
              headline: topic.headline,
              description: topic.description,
              inLanguage: 'pt-BR',
              url: `${SITE_URL}/artigos#${topic.id}`,
              author: {
                '@type': 'Organization',
                name: 'Gaia & Sena Advogados Associados'
              }
            }
          }))
        }
      })
      this.structuredDataScript = markRaw(structuredDataScript)
      document.head.appendChild(structuredDataScript)
    },
    async loadArticles() {
      if (this.requestController) {
        this.requestController.abort()
      }

      const controller = new AbortController()
      let timedOut = false
      const timeout = window.setTimeout(() => {
        timedOut = true
        controller.abort()
      }, 12000)
      this.requestController = markRaw(controller)
      this.loading = true
      this.error = ''

      try {
        const response = await fetch(FEED_URL, {
          signal: controller.signal,
          headers: { Accept: 'application/json' }
        })

        if (!response.ok) {
          throw new Error(`A fonte de notícias respondeu com status ${response.status}.`)
        }

        const feed = await response.json()

        if (feed.status !== 'ok' || !Array.isArray(feed.items)) {
          throw new Error('A fonte de notícias retornou uma resposta inválida.')
        }

        this.articles = feed.items
          .map((item) => ({
            title: stripHtml(item.title),
            link: getArticleLink(item.link),
            summary: stripHtml(item.description || item.content).slice(0, 260),
            publishedAt: item.pubDate && !Number.isNaN(Date.parse(item.pubDate))
              ? new Date(item.pubDate).toISOString()
              : ''
          }))
          .filter((article) => article.title && article.link)
      } catch (error) {
        if (error.name !== 'AbortError' || timedOut) {
          this.error = 'Não foi possível carregar as notícias jurídicas agora. Verifique sua conexão e tente novamente.'
        }
      } finally {
        window.clearTimeout(timeout)
        if (this.requestController === controller) {
          this.requestController = null
          this.loading = false
        }
      }
    },
    formatDate(date) {
      return new Intl.DateTimeFormat('pt-BR', {
        day: '2-digit',
        month: 'long',
        year: 'numeric'
      }).format(new Date(date))
    }
  }
}
</script>

